#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
arm_kinematics.py — обратная кинематика 3-звенной руки + точки перекладки.

За основу взята кинематика техника (solve_ik из его 2.py): длины звеньев
100/140/160, поворот базы через atan2(x, y). Математика его, но параметры
вынесены наверх в один блок, чтобы менять под реальную руку, не трогая код.

============================================================================
                     КАК УСТРОЕНО УПРАВЛЕНИЕ РУКОЙ
============================================================================
Рука имеет 3 поворотных сустава (сервомотора) + клешню:

   [БАЗА] --поворот вокруг вертикали--> [ПЛЕЧО] --> [ЛОКОТЬ] --> [КЛЕШНЯ]
     s0                                    s1          s2         grip

  s0 (БАЗА)   — поворачивает всю руку влево/вправо. atan2(x, y): ноль когда
                товар прямо по оси Y перед рукой, +90 в offsete (см. код).
  s1 (ПЛЕЧО)  — поднимает первое звено (длиной L2).
  s2 (ЛОКОТЬ) — сгибает второе звено (длиной L3) относительно первого.
  grip        — клешня: GRIP_OPEN раскрыта, GRIP_CLOSE зажата (углы ниже).

Перекладка идёт НЕ одним движением, а циклом из трёх точек (как у техника):
  PICK — опуститься к товару и зажать
  LIFT — поднять вверх на безопасную высоту (не задеть борт кейджа)
  DROP — перенести в нужный ящик (C, D или R) и отпустить
Углы всех трёх точек считает Pi и шлёт на Arduino одной командой SEQ.

ВАЖНО про "мёртвые зоны": не любая точка достижима. Если товар слишком
далеко/близко или угол выходит за предел сервы — solve_ik бросает ValueError,
и поток отправляет товар в разбор (R), а не роняет программу.
============================================================================
"""

import math

# ############################################################################
# #                                                                          #
# #   ПАРАМЕТРЫ РУКИ — МЕНЯТЬ ЗДЕСЬ ПОД РЕАЛЬНУЮ РУКУ                          #
# #                                                                          #
# ############################################################################

# --- ДЛИНЫ ЗВЕНЬЕВ (мм) — значения техника ----------------------------------
L1 = 100.0   # высота основания: от стола до первого сустава (плеча)
L2 = 140.0   # длина плеча:     от плеча до локтя
L3 = 160.0   # длина предплечья: от локтя до кончика клешни

# --- ФИКСИРОВАННАЯ ТОЧКА ПОДБОРА --------------------------------------------
# Куда конвейер ВСЕГДА привозит товар для захвата (в мм от основания руки).
# Зрение уточняет её по конкретному товару, но это базовая точка стола.
POINT_PICK = {"x": 0.0, "y": 180.0, "z": 20.0}

# --- БЕЗОПАСНАЯ ВЫСОТА ПОДЪЁМА -----------------------------------------------
# На сколько мм поднять товар вверх после захвата, прежде чем нести к ящику.
# Должна быть больше высоты борта кейджа, иначе заденет.
SAFE_Z_OFFSET = 70.0

# --- ТОЧКИ СБРОСА по категориям (мм от основания руки) ----------------------
# Куда рука относит товар каждой категории. Замерить на реальной установке.
DROP_ZONES = {
    "C": {"x":  150.0, "y": 120.0, "z": 40.0},   # ящик негабарита (справа)
    "D": {"x": -150.0, "y": 120.0, "z": 40.0},   # ящик круглых (слева)
    "R": {"x":    0.0, "y": 230.0, "z": 30.0},   # брак / ручной разбор (прямо)
}

# --- УГЛЫ КЛЕШНИ (градусы) — значения техника из Arduino ---------------------
GRIP_OPEN  = 30    # клешня раскрыта
GRIP_CLOSE = 110   # клешня зажата на детали

# --- ПОПРАВКА УГЛА БАЗЫ ------------------------------------------------------
# atan2(x, y) даёт ноль, когда товар прямо перед рукой. Серва базы стоит
# в среднем положении 90°, поэтому к математическому углу прибавляем это.
BASE_OFFSET_DEG = 90

# ############################################################################
# #                  КОНЕЦ БЛОКА ПАРАМЕТРОВ. НИЖЕ — МАТЕМАТИКА.               #
# ############################################################################


def solve_ik(x, y, z):
    """Точка (x, y, z) в мм -> углы (база, плечо, локоть) в градусах.

    Математика техника без изменений. Бросает ValueError, если точка вне
    зоны досягаемости — вызывающий код это ловит и шлёт товар в R.
    """
    # угол поворота базы вокруг вертикали
    base = math.atan2(x, y)

    # расстояние до точки в плоскости XY и по высоте
    r = math.hypot(x, y)
    dz = z - L1                          # высота относительно первого сустава

    # прямое расстояние от плеча до цели
    d = math.hypot(r, dz)

    # проверка достижимости: точка в кольце [|L2-L3|, L2+L3]
    if d > (L2 + L3) or d < abs(L2 - L3):
        raise ValueError(f"точка ({x:.0f},{y:.0f},{z:.0f}) вне досягаемости, d={d:.1f}")

    # локоть по теореме косинусов
    cos_elbow = (L2**2 + L3**2 - d**2) / (2 * L2 * L3)
    elbow_rad = math.pi - math.acos(max(-1.0, min(1.0, cos_elbow)))

    # плечо: наклон на цель плюс поправка из треугольника
    alpha = math.atan2(dz, r)
    cos_shoulder = (L2**2 + d**2 - L3**2) / (2 * L2 * d)
    beta = math.acos(max(-1.0, min(1.0, cos_shoulder)))
    shoulder_rad = alpha + beta

    # перевод в градусы серв (0..180)
    a_base = int(math.degrees(base) + BASE_OFFSET_DEG)
    a_shoulder = int(math.degrees(shoulder_rad))
    a_elbow = int(math.degrees(elbow_rad))
    return a_base, a_shoulder, a_elbow


def calculate_trajectory(zone_category, pick_point=None):
    """Три точки перекладки для товара: PICK -> LIFT -> DROP.

    zone_category — 'C', 'D' или 'R': куда нести товар.
    pick_point    — куда опускаться за товаром. Если None, берётся POINT_PICK.
                    Зрение передаёт сюда уточнённую точку конкретного товара.

    Возвращает (pick_angles, lift_angles, drop_angles) — по три угла на каждую.
    Бросает ValueError, если любая точка недостижима.
    """
    pk = pick_point if pick_point else POINT_PICK
    drop = DROP_ZONES.get(zone_category, DROP_ZONES["R"])

    pick = solve_ik(pk["x"], pk["y"], pk["z"])
    lift = solve_ik(pk["x"], pk["y"], pk["z"] + SAFE_Z_OFFSET)   # тот же XY, выше
    drop_a = solve_ik(drop["x"], drop["y"], drop["z"])
    return pick, lift, drop_a
